package main

// history_chats.txt is a standard part of a profile: without it history-sync replay
// stays OFF (fail closed, see history.go). `run`, `pair`, `history-check` and scripts/ensure.sh warn
// loudly when it is missing, and a COMMENTED-OUT candidate list is scaffolded at
// history_chats.txt.suggested from the chats the profile already routes (inbound lines in
// inbox.jsonl, named from joined groups / contacts / push names). Nothing here ever enables replay:
// a human (whoever owns the profile) copies the lines they want into history_chats.txt and uncomments
// them. Chats whose name looks like a shared display (screen, tablet, kiosk, TV, ...) are listed as
// EXCLUDED. Names are chat display names only; no message text is read into these files.

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"go.mau.fi/whatsmeow/types"
)

const HistorySuggestedFile = "history_chats.txt.suggested"

// historyMissingWarning is "" when <dir>/history_chats.txt exists, else a loud one-line warning.
func historyMissingWarning(dir, profile string) string {
	if _, err := os.Stat(filepath.Join(dir, HistoryChatsFile)); err == nil {
		return ""
	}
	return fmt.Sprintf("!!! WARNING %s: %s missing: history-sync replay is OFF (messages sent while logged out are lost on re-link). "+
		"Review %s, copy the wanted lines to %s and uncomment them.",
		profile, HistoryChatsFile, filepath.Join(dir, HistorySuggestedFile), filepath.Join(dir, HistoryChatsFile))
}

type chatCand struct {
	JID     string
	Name    string
	Inbound int
	Last    string
}

var sharedDisplayRe = regexp.MustCompile(`(?i)display|screen|pantalla|tablet|kiosk|\btv\b|televis`)

// historyCandidates lists chats with at least one inbound (not from_me, not update) line in the inbox,
// busiest first. Name: push name of the latest inbound line for 1:1 chats ("" for groups).
func historyCandidates(inboxPath string) []chatCand {
	f, err := os.Open(inboxPath)
	if err != nil {
		return nil
	}
	defer f.Close()
	by := map[string]*chatCand{}
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 64*1024), 16*1024*1024)
	for sc.Scan() {
		var m struct {
			Chat     string `json:"chat"`
			FromMe   bool   `json:"from_me"`
			IsGroup  bool   `json:"is_group"`
			PushName string `json:"push_name"`
			TS       string `json:"ts"`
			Type     string `json:"type"`
		}
		if json.Unmarshal(sc.Bytes(), &m) != nil || m.Chat == "" || m.FromMe || isUpdateLine(m.Type) {
			continue
		}
		j, err := types.ParseJID(m.Chat)
		if err != nil || (j.Server != types.GroupServer && j.Server != types.DefaultUserServer && j.Server != types.HiddenUserServer) {
			continue
		}
		k := j.ToNonAD().String()
		c := by[k]
		if c == nil {
			c = &chatCand{JID: k}
			by[k] = c
		}
		c.Inbound++
		if m.TS > c.Last {
			c.Last = m.TS
			if !m.IsGroup && j.Server != types.GroupServer && m.PushName != "" {
				c.Name = m.PushName
			}
		}
	}
	out := make([]chatCand, 0, len(by))
	for _, c := range by {
		out = append(out, *c)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Inbound != out[j].Inbound {
			return out[i].Inbound > out[j].Inbound
		}
		return out[i].JID < out[j].JID
	})
	return out
}

func oneLineName(s string) string {
	s = strings.Join(strings.Fields(strings.ReplaceAll(s, "#", "")), " ")
	if len([]rune(s)) > 60 {
		s = string([]rune(s)[:60])
	}
	return s
}

// writeHistorySuggested (re)writes <dir>/history_chats.txt.suggested atomically; names (JID -> display
// name, optional) override inbox push names. Returns the number of candidate (non-excluded) chats.
func writeHistorySuggested(dir, profile string, names map[string]string, now time.Time) (int, error) {
	cands := historyCandidates(filepath.Join(dir, "inbox.jsonl"))
	var b strings.Builder
	fmt.Fprintf(&b, "# history_chats.txt CANDIDATES for profile %s (generated by wabridge %s; regenerated, do not edit).\n", profile, now.Format("2006-01-02 15:04 MST"))
	b.WriteString("# NOT ENABLED. Every line is commented out. To enable replay for a chat, copy its line to\n")
	b.WriteString("# history_chats.txt in this directory and remove the leading '# '. The profile owner approves the list.\n")
	b.WriteString("# Source: chats with inbound lines in inbox.jsonl, busiest first. Names are chat display names.\n")
	n := 0
	for _, c := range cands {
		name := c.Name
		if v := names[c.JID]; v != "" {
			name = v
		}
		name = oneLineName(name)
		if name == "" {
			name = "(name unknown)"
		}
		last := c.Last
		if len(last) >= 10 {
			last = last[:10]
		}
		if sharedDisplayRe.MatchString(name) {
			fmt.Fprintf(&b, "# EXCLUDED (shared display): %s  # %s\n", c.JID, name)
			continue
		}
		fmt.Fprintf(&b, "# %s  # %s; %d inbound, last %s\n", c.JID, name, c.Inbound, last)
		n++
	}
	if len(cands) == 0 {
		b.WriteString("# (no inbound chats in inbox.jsonl yet)\n")
	}
	p := filepath.Join(dir, HistorySuggestedFile)
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o600); err != nil {
		return 0, err
	}
	return n, os.Rename(tmp, p)
}

// appendBridgeLog adds one timestamped line to <dir>/bridge.log (used where stderr is not the log).
func appendBridgeLog(dir, line string) {
	f, err := os.OpenFile(filepath.Join(dir, "bridge.log"), os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	defer f.Close()
	fmt.Fprintf(f, "%s %s\n", time.Now().Format("2006-01-02 15:04:05"), line)
}

// historyCheckCmd: `wabridge history-check --profile P [--write-suggested]`. No WhatsApp connection,
// never opens session.db. Prints the warning to stderr and exits 4 when history_chats.txt is missing,
// 0 otherwise. Scaffolds the .suggested file when missing (or always with --write-suggested).
func historyCheckCmd(args []string) {
	profile, force := "", false
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--profile":
			if i+1 < len(args) {
				profile = args[i+1]
				i++
			}
		case "--write-suggested":
			force = true
		}
	}
	if profile == "" {
		die("usage: wabridge history-check --profile NAME [--write-suggested]")
	}
	dir := profileDir(profile)
	if _, err := os.Stat(filepath.Join(dir, HistorySuggestedFile)); force || err != nil {
		if n, err := writeHistorySuggested(dir, profile, nil, time.Now()); err != nil {
			fmt.Fprintln(os.Stderr, "history-check: writing suggestions failed:", err)
		} else {
			fmt.Fprintf(os.Stderr, "history-check: %s: %d candidate chat(s) in %s (commented out, not enabled)\n", profile, n, HistorySuggestedFile)
		}
	}
	if w := historyMissingWarning(dir, profile); w != "" {
		fmt.Fprintln(os.Stderr, w)
		os.Exit(4)
	}
	fmt.Printf("%s: %s present (%d chat(s))\n", profile, HistoryChatsFile, len(loadHistoryChats(dir)))
}
